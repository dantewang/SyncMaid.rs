//! Turns `lang/*.json` into a Rust module of typed accessors.
//!
//! The point of generating rather than looking up by name at runtime: **a key that does not
//! exist is a compile error, and so is calling one with the wrong number of arguments.** There
//! is no "missing key" case to handle at runtime because there is no way to write one.
//!
//! English is the authority. Every other language must carry exactly the same keys — a build
//! that finds otherwise fails rather than shipping a window with holes in it. An entry that is
//! present but empty falls back to English with a warning, because a blank label is worse than
//! an untranslated one.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The languages that ship, in the order the settings page offers them.
const LANGUAGES: [(&str, &str); 4] = [
    ("en", "en.json"),
    ("zh-Hans", "zh-Hans.json"),
    ("zh-Hant", "zh-Hant.json"),
    ("ja", "ja.json"),
];

/// The key naming the language in its own words, which is how the picker lists it.
const NAME_KEY: &str = "Meta.LanguageName";

pub fn generate() {
    let directory = Path::new("lang");
    println!("cargo:rerun-if-changed=lang");

    let english = super::read_table(&directory.join("en.json"));
    let tables: Vec<(&str, BTreeMap<String, String>)> = LANGUAGES
        .iter()
        .map(|(tag, file)| {
            let path = directory.join(file);
            println!("cargo:rerun-if-changed={}", path.display());
            (*tag, super::read_table(&path))
        })
        .collect();

    for (tag, table) in &tables {
        check_keys(tag, &english, table);
    }

    let keys: Vec<&String> = english.keys().collect();
    let mut out = String::new();
    write_header(&mut out, keys.len());
    write_tables(&mut out, &keys, &english, &tables);
    write_keys(&mut out, &keys);
    write_accessors(&mut out, &keys, &english);

    let target = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("strings.rs");
    std::fs::write(&target, out).unwrap_or_else(|error| panic!("write strings.rs: {error}"));
}

/// A language with a key the others do not have — or missing one they do — makes a window with
/// holes in it. Better to not build at all.
fn check_keys(tag: &str, english: &BTreeMap<String, String>, table: &BTreeMap<String, String>) {
    let missing: Vec<&str> = english
        .keys()
        .filter(|key| !table.contains_key(*key))
        .map(String::as_str)
        .collect();
    let extra: Vec<&str> = table
        .keys()
        .filter(|key| !english.contains_key(*key))
        .map(String::as_str)
        .collect();

    if !missing.is_empty() {
        panic!("lang/{tag}.json is missing: {}", missing.join(", "));
    }
    if !extra.is_empty() {
        panic!(
            "lang/{tag}.json has keys English does not: {}",
            extra.join(", ")
        );
    }
}

fn write_header(out: &mut String, count: usize) {
    out.push_str("// @generated by build.rs from crates/app/lang/*.json. Do not edit by hand.\n\n");
    let _ = writeln!(out, "/// How many strings every table holds.");
    let _ = writeln!(out, "pub const COUNT: usize = {count};\n");
    out.push_str(
        "/// One shipped language, with its whole table in key order.\n\
         pub struct Language {\n    \
             /// The BCP-47 tag stored in settings.json.\n    \
             pub tag: &'static str,\n    \
             /// What this language calls itself, which is how the picker lists it.\n    \
             pub name: &'static str,\n    \
             pub strings: [&'static str; COUNT],\n\
         }\n\n",
    );
}

fn write_tables(
    out: &mut String,
    keys: &[&String],
    english: &BTreeMap<String, String>,
    tables: &[(&str, BTreeMap<String, String>)],
) {
    let _ = writeln!(
        out,
        "/// Every shipped language, in the order the settings page offers them."
    );
    let _ = writeln!(
        out,
        "pub static LANGUAGES: [Language; {}] = [",
        tables.len()
    );

    for (tag, table) in tables {
        let name = table
            .get(NAME_KEY)
            .filter(|name| !name.is_empty())
            .unwrap_or_else(|| panic!("lang/{tag}.json needs {NAME_KEY}"));

        let _ = writeln!(out, "    Language {{");
        let _ = writeln!(out, "        tag: {},", quote(tag));
        let _ = writeln!(out, "        name: {},", quote(name));
        let _ = writeln!(out, "        strings: [");
        for key in keys {
            let value = match table.get(*key) {
                Some(value) if !value.is_empty() => value,
                // Blank is worse than untranslated: the window would show nothing at all.
                _ => {
                    println!("cargo:warning=lang/{tag}.json has no text for {key}");
                    &english[*key]
                }
            };
            let _ = writeln!(out, "            {}, // {key}", quote(value));
        }
        let _ = writeln!(out, "        ],");
        let _ = writeln!(out, "    }},");
    }
    let _ = writeln!(out, "];\n");
}

fn write_keys(out: &mut String, keys: &[&String]) {
    let _ = writeln!(out, "/// Every key's position in a language's table.");
    let _ = writeln!(out, "pub mod key {{");
    for (index, key) in keys.iter().enumerate() {
        let _ = writeln!(
            out,
            "    pub const {}: usize = {index}; // {key}",
            identifier(key).to_uppercase()
        );
    }
    let _ = writeln!(out, "}}\n");
}

/// One function per key: a plain one, a formatting one, or a plural pair collapsed into one.
fn write_accessors(out: &mut String, keys: &[&String], english: &BTreeMap<String, String>) {
    for key in keys {
        if key.as_str() == NAME_KEY {
            continue; // Belongs to the picker, not to the window.
        }

        // `X.One` / `X.Other` are one idea with two spellings; the count decides which.
        if let Some(base) = key.strip_suffix(".One") {
            let other = format!("{base}.Other");
            if english.contains_key(&other) {
                let _ = writeln!(
                    out,
                    "/// `{}` / `{}`\npub fn {}(count: i64) -> String {{\n    \
                     crate::i18n::plural(key::{}, key::{}, count)\n}}\n",
                    escape_doc(&english[*key]),
                    escape_doc(&english[&other]),
                    identifier(base),
                    identifier(key).to_uppercase(),
                    identifier(&other).to_uppercase(),
                );
            }
            continue;
        }
        if key.ends_with(".Other") {
            continue; // Written with its `.One`.
        }

        let value = &english[*key];
        let arity = placeholder_count(value);
        let name = identifier(key);

        if arity == 0 {
            let _ = writeln!(
                out,
                "/// `{}`\npub fn {name}() -> &'static str {{\n    crate::i18n::text(key::{})\n}}\n",
                escape_doc(value),
                name.to_uppercase(),
            );
            continue;
        }

        let parameters: Vec<String> = (0..arity)
            .map(|index| format!("a{index}: impl std::fmt::Display"))
            .collect();
        let arguments: Vec<String> = (0..arity).map(|index| format!("&a{index}")).collect();
        let _ = writeln!(
            out,
            "/// `{}`\npub fn {name}({}) -> String {{\n    \
             crate::i18n::format(key::{}, &[{}])\n}}\n",
            escape_doc(value),
            parameters.join(", "),
            name.to_uppercase(),
            arguments.join(", "),
        );
    }
}

/// How many `{N}` slots a string has, which is how many arguments its function takes.
fn placeholder_count(value: &str) -> usize {
    let mut highest: Option<usize> = None;
    let bytes: Vec<char> = value.chars().collect();
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == '{' {
            let mut end = index + 1;
            while end < bytes.len() && bytes[end].is_ascii_digit() {
                end += 1;
            }
            if end > index + 1 && bytes.get(end) == Some(&'}') {
                let slot: usize = bytes[index + 1..end]
                    .iter()
                    .collect::<String>()
                    .parse()
                    .ok()
                    .unwrap_or(0);
                highest = Some(highest.map_or(slot, |seen: usize| seen.max(slot)));
                index = end;
            }
        }
        index += 1;
    }
    highest.map_or(0, |highest| highest + 1)
}

/// `Task.NextRunFormat` -> `task_next_run_format`.
fn identifier(key: &str) -> String {
    let mut out = String::with_capacity(key.len() + 8);
    for (index, character) in key.chars().enumerate() {
        if character == '.' {
            out.push('_');
        } else if character.is_ascii_uppercase() {
            // A word boundary inside a segment: `NextRun` -> `next_run`.
            if index > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.push(character.to_ascii_lowercase());
        } else {
            out.push(character);
        }
    }
    out
}

fn quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            _ => out.push(character),
        }
    }
    out.push('"');
    out
}

/// Doc comments are markdown, and a stray backtick or newline in a string would break them.
fn escape_doc(value: &str) -> String {
    value.replace(['\n', '\r'], " ").replace('`', "'")
}
